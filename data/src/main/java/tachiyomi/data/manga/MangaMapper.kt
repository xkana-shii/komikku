package tachiyomi.data.manga

import eu.kanade.tachiyomi.source.model.UpdateStrategy
import kotlinx.serialization.json.JsonObject
import tachiyomi.domain.library.model.LibraryManga
import tachiyomi.domain.manga.model.Manga
import tachiyomi.domain.manga.model.MangaWithChapterCount
import kotlin.time.Instant

object MangaMapper {
    fun mapManga(
        id: Long,
        sourceId: Long,
        remoteUrl: String,
        remoteTitle: String,
        remoteAuthor: String?,
        remoteArtist: String?,
        remoteDescription: String?,
        remoteGenre: List<String>?,
        remoteStatus: Long,
        remoteCover: String?,
        remoteUpdateStrategy: UpdateStrategy,
        remoteMemo: JsonObject,
        userFavoriteAt: Instant?,
        userNotes: String,
        userReaderFlags: Long,
        userChapterFlags: Long,
        stateChapterLastUpdate: Instant?,
        stateChapterNextUpdate: Instant?,
        stateChapterFetchInterval: Long,
        stateCoverLastModified: Instant?,
        stateInitialized: Boolean,
        lastModifiedAt: Long,
        version: Long,
        isSyncing: Long,
        favoriteModifiedAt: Long?,
        // KNS -->
        userBlacklistedChapters: List<String>,
        userScanlatorPriority: List<String>,
        userScanlatorRangeRules: List<String>,
        userSmartMergeOverride: Boolean?,
        // KNS <--
        // SY -->
        userTitle: String?,
        userAuthor: String?,
        userArtist: String?,
        userThumbnailUrl: String?,
        userDescription: String?,
        userGenre: List<String>?,
        userStatus: Long?,
        // SY <--
    ): Manga = Manga(
        id = id,
        source = sourceId,
        favorite = userFavoriteAt != null,
        lastUpdate = stateChapterLastUpdate,
        nextUpdate = stateChapterNextUpdate,
        fetchInterval = stateChapterFetchInterval.toInt(),
        dateAdded = userFavoriteAt,
        viewerFlags = userReaderFlags,
        chapterFlags = userChapterFlags,
        coverLastModified = stateCoverLastModified,
        url = remoteUrl,
        // SY -->
        ogTitle = remoteTitle,
        ogArtist = remoteArtist,
        ogAuthor = remoteAuthor,
        ogThumbnailUrl = remoteCover,
        ogDescription = remoteDescription,
        ogGenre = remoteGenre,
        ogStatus = remoteStatus,
        // SY <--
        updateStrategy = remoteUpdateStrategy,
        initialized = stateInitialized,
        lastModifiedAt = lastModifiedAt,
        favoriteModifiedAt = favoriteModifiedAt,
        version = version,
        notes = userNotes,
        memo = remoteMemo,
        // SY -->
        userTitle = userTitle,
        userAuthor = userAuthor,
        userArtist = userArtist,
        userThumbnailUrl = userThumbnailUrl,
        userDescription = userDescription,
        userGenre = userGenre,
        userStatus = userStatus,
        // SY <--
        // KNS -->
        blacklistedChapters = userBlacklistedChapters,
        scanlatorPriority = userScanlatorPriority,
        scanlatorRangeRules = userScanlatorRangeRules,
        smartMergeOverride = userSmartMergeOverride,
        // KNS <--
    )

    fun mapLibraryManga(
        id: Long,
        sourceId: Long,
        remoteUrl: String,
        remoteTitle: String,
        remoteAuthor: String?,
        remoteArtist: String?,
        remoteDescription: String?,
        remoteGenre: List<String>?,
        remoteStatus: Long,
        remoteCover: String?,
        remoteUpdateStrategy: UpdateStrategy,
        remoteMemo: JsonObject,
        userFavoriteAt: Instant?,
        userNotes: String,
        userReaderFlags: Long,
        userChapterFlags: Long,
        stateChapterLastUpdate: Instant?,
        stateChapterNextUpdate: Instant?,
        stateChapterFetchInterval: Long,
        stateCoverLastModified: Instant?,
        stateInitialized: Boolean,
        lastModifiedAt: Long,
        version: Long,
        isSyncing: Long,
        favoriteModifiedAt: Long?,
        // KNS -->
        userBlacklistedChapters: List<String>,
        userScanlatorPriority: List<String>,
        userScanlatorRangeRules: List<String>,
        userSmartMergeOverride: Boolean?,
        // KNS <--
        // SY -->
        userTitle: String?,
        userAuthor: String?,
        userArtist: String?,
        userThumbnailUrl: String?,
        userDescription: String?,
        userGenre: List<String>?,
        userStatus: Long?,
        // SY <--
        totalCount: Long,
        readCount: Double,
        latestUpload: Instant?,
        chapterFetchedAt: Instant?,
        lastRead: Instant?,
        bookmarkCount: Double,
        // KMK -->
        bookmarkedReadCount: Long,
        // KMK <--
        categories: String,
    ): LibraryManga = LibraryManga(
        manga = mapManga(
            id,
            sourceId,
            remoteUrl,
            remoteTitle,
            remoteAuthor,
            remoteArtist,
            remoteDescription,
            remoteGenre,
            remoteStatus,
            remoteCover,
            remoteUpdateStrategy,
            remoteMemo,
            userFavoriteAt,
            userNotes,
            userReaderFlags,
            userChapterFlags,
            stateChapterLastUpdate,
            stateChapterNextUpdate,
            stateChapterFetchInterval,
            stateCoverLastModified,
            stateInitialized,
            lastModifiedAt,
            version,
            isSyncing,
            favoriteModifiedAt,
            // KNS -->
            userBlacklistedChapters,
            userScanlatorPriority,
            userScanlatorRangeRules,
            userSmartMergeOverride,
            // KNS <--
            // SY -->
            userTitle,
            userAuthor,
            userArtist,
            userThumbnailUrl,
            userDescription,
            userGenre,
            userStatus,
            // SY <--
        ),
        categories = categories.split(",").map { it.toLong() },
        totalChapters = totalCount,
        readCount = readCount.toLong(),
        bookmarkCount = bookmarkCount.toLong(),
        // KMK -->
        bookmarkReadCount = bookmarkedReadCount,
        chapterFlags = userChapterFlags,
        // KMK <--
        latestUpload = latestUpload,
        chapterFetchedAt = chapterFetchedAt,
        lastRead = lastRead,
    )

