package tachiyomi.data.manga

import eu.kanade.tachiyomi.source.model.UpdateStrategy
import kotlinx.serialization.json.JsonObject
import tachiyomi.domain.library.model.LibraryManga
import tachiyomi.domain.manga.model.Manga
import tachiyomi.domain.manga.model.MangaWithChapterCount

object MangaMapper {
    fun mapManga(
        id: Long,
        sourceId: Long,
        remoteUrl: String,
        remoteTitle: String,
        remoteAuthor: String?,
        remoteArtist: String?,
        remoteDescription: String?,
        remoteGenre: List<String>?,
        remoteStatus: Long,
        remoteCover: String?,
        remoteUpdateStrategy: UpdateStrategy,
        remoteMemo: JsonObject,
        userFavoriteAt: Long?,
        userNotes: String,
        userReaderFlags: Long,
        userChapterFlags: Long,
        @Suppress("UNUSED_PARAMETER")
        userFilteredScanlators: String?,
        stateChapterLastUpdate: Long?,
        stateChapterNextUpdate: Long?,
        stateChapterFetchInterval: Long,
        stateCoverLastModified: Long,
        stateInitialized: Boolean,
        stateDateAdded: Long,
        stateLastModifiedAt: Long,
        stateVersion: Long,
        @Suppress("UNUSED_PARAMETER")
        stateIsSyncing: Long,
    ): Manga = Manga(
        id = id,
        source = sourceId,
        favorite = userFavoriteAt != null,
        lastUpdate = stateChapterLastUpdate ?: 0,
        nextUpdate = stateChapterNextUpdate ?: 0,
        fetchInterval = stateChapterFetchInterval.toInt(),
        dateAdded = stateDateAdded,
        viewerFlags = userReaderFlags,
        chapterFlags = userChapterFlags,
        coverLastModified = stateCoverLastModified,
        url = remoteUrl,
        ogTitle = remoteTitle,
        ogArtist = remoteArtist,
        ogAuthor = remoteAuthor,
        ogThumbnailUrl = remoteCover,
        ogDescription = remoteDescription,
        ogGenre = remoteGenre,
        ogStatus = remoteStatus,
        updateStrategy = remoteUpdateStrategy,
        initialized = stateInitialized,
        lastModifiedAt = stateLastModifiedAt,
        favoriteModifiedAt = userFavoriteAt,
        version = stateVersion,
        notes = userNotes,
        memo = remoteMemo,
    )

    fun mapLibraryManga(
        id: Long,
        sourceId: Long,
        remoteUrl: String,
        remoteTitle: String,
        remoteAuthor: String?,
        remoteArtist: String?,
        remoteDescription: String?,
        remoteGenre: List<String>?,
        remoteStatus: Long,
        remoteCover: String?,
        remoteUpdateStrategy: UpdateStrategy,
        remoteMemo: JsonObject,
        userFavoriteAt: Long?,
        userNotes: String,
        userReaderFlags: Long,
        userChapterFlags: Long,
        userFilteredScanlators: String?,
        stateChapterLastUpdate: Long?,
        stateChapterNextUpdate: Long?,
        stateChapterFetchInterval: Long,
        stateCoverLastModified: Long,
        stateInitialized: Boolean,
        stateDateAdded: Long,
        stateLastModifiedAt: Long,
        stateVersion: Long,
        stateIsSyncing: Long,
        totalCount: Long,
        readCount: Double,
        latestUpload: Long,
        chapterFetchedAt: Long,
        lastRead: Long,
        bookmarkCount: Double,
        fillermarkCount: Double,
        bookmarkedReadCount: Long,
        fillermarkedReadCount: Long,
        categories: String,
    ): LibraryManga = LibraryManga(
        manga = mapManga(
            id = id,
            sourceId = sourceId,
            remoteUrl = remoteUrl,
            remoteTitle = remoteTitle,
            remoteAuthor = remoteAuthor,
            remoteArtist = remoteArtist,
            remoteDescription = remoteDescription,
            remoteGenre = remoteGenre,
            remoteStatus = remoteStatus,
            remoteCover = remoteCover,
            remoteUpdateStrategy = remoteUpdateStrategy,
            remoteMemo = remoteMemo,
            userFavoriteAt = userFavoriteAt,
            userNotes = userNotes,
            userReaderFlags = userReaderFlags,
            userChapterFlags = userChapterFlags,
            userFilteredScanlators = userFilteredScanlators,
            stateChapterLastUpdate = stateChapterLastUpdate,
            stateChapterNextUpdate = stateChapterNextUpdate,
            stateChapterFetchInterval = stateChapterFetchInterval,
            stateCoverLastModified = stateCoverLastModified,
            stateInitialized = stateInitialized,
            stateDateAdded = stateDateAdded,
            stateLastModifiedAt = stateLastModifiedAt,
            stateVersion = stateVersion,
            stateIsSyncing = stateIsSyncing,
        ),
        categories = categories.split(",").map { it.toLong() },
        totalChapters = totalCount,
        readCount = readCount.toLong(),
        bookmarkCount = bookmarkCount.toLong(),
        fillermarkCount = fillermarkCount.toLong(),
        bookmarkReadCount = bookmarkedReadCount,
        fillermarkReadCount = fillermarkedReadCount,
        chapterFlags = userChapterFlags,
        latestUpload = latestUpload,
        chapterFetchedAt = chapterFetchedAt,
        lastRead = lastRead,
    )

    fun mapMangaWithChapterCount(
        id: Long,
        sourceId: Long,
        remoteUrl: String,
        remoteTitle: String,
        remoteAuthor: String?,
        remoteArtist: String?,
        remoteDescription: String?,
        remoteGenre: List<String>?,
        remoteStatus: Long,
        remoteCover: String?,
        remoteUpdateStrategy: UpdateStrategy,
        remoteMemo: JsonObject,
        userFavoriteAt: Long?,
        userNotes: String,
        userReaderFlags: Long,
        userChapterFlags: Long,
        userFilteredScanlators: String?,
        stateChapterLastUpdate: Long?,
        stateChapterNextUpdate: Long?,
        stateChapterFetchInterval: Long,
        stateCoverLastModified: Long,
        stateInitialized: Boolean,
        stateDateAdded: Long,
        stateLastModifiedAt: Long,
        stateVersion: Long,
        stateIsSyncing: Long,
        chapterCount: Long,
    ): MangaWithChapterCount = MangaWithChapterCount(
        manga = mapManga(
            id = id,
            sourceId = sourceId,
            remoteUrl = remoteUrl,
            remoteTitle = remoteTitle,
            remoteAuthor = remoteAuthor,
            remoteArtist = remoteArtist,
            remoteDescription = remoteDescription,
            remoteGenre = remoteGenre,
            remoteStatus = remoteStatus,
            remoteCover = remoteCover,
            remoteUpdateStrategy = remoteUpdateStrategy,
            remoteMemo = remoteMemo,
            userFavoriteAt = userFavoriteAt,
            userNotes = userNotes,
            userReaderFlags = userReaderFlags,
            userChapterFlags = userChapterFlags,
            userFilteredScanlators = userFilteredScanlators,
            stateChapterLastUpdate = stateChapterLastUpdate,
            stateChapterNextUpdate = stateChapterNextUpdate,
            stateChapterFetchInterval = stateChapterFetchInterval,
            stateCoverLastModified = stateCoverLastModified,
            stateInitialized = stateInitialized,
            stateDateAdded = stateDateAdded,
            stateLastModifiedAt = stateLastModifiedAt,
            stateVersion = stateVersion,
            stateIsSyncing = stateIsSyncing,
        ),
        chapterCount = chapterCount,
    )
}
